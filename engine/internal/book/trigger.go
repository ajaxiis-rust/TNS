package book

// BookWindowID — идентификатор модального окна «Моя книга» (T-07-11, шаг 3):
// оба входа — кнопка BOOK в чате и вкладка «История» верхнего меню — ведут на
// одно и то же окно, поэтому идентификатор не зависит от входа (CB-12.1).
const BookWindowID = "book"

// Trigger — триггер работы с книгой (CB-12): переводит точку входа (кнопка BOOK
// в чате или вкладка «История» верхнего меню) в модальное окно «Моя книга».
// Триггер — точка входа, в базы не пишет.
type Trigger struct {
	Entry WindowEntry
}

// WindowID возвращает идентификатор модального окна, на которое ведёт триггер.
// Идентификатор одинаков для обоих входов (шаг 3).
func (t Trigger) WindowID() string {
	return BookWindowID
}

// Tabs возвращает состав вкладок окна, открываемого триггером (шаг 2): тот же
// состав независимо от входа.
func (t Trigger) Tabs() []WindowTab {
	return WindowTabs()
}
