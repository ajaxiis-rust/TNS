// profileSet — развёрнутые множества лемм профиля для быстрой сверки.
type profileSet struct {
	function map[string]struct{}
	toponym  map[string]struct{}
	common   map[string]struct{}
	speech   map[string]struct{}
}

// build разворачивает профиль в множества лемм (нижний регистр).
func (p LangProfile) build() profileSet {
	return profileSet{
		function: setOf(p.FunctionLemmas),
		toponym:  setOf(p.ToponymLemmas),
		common:   setOf(p.CommonLemmas),
		speech:   setOf(p.SpeechLemmas),
	}
}

// setOf собирает множество лемм в нижнем регистре; пустые записи пропускаются.
func setOf(items []string) map[string]struct{} {
	out := make(map[string]struct{}, len(items))
	for _, s := range items {
		s = strings.ToLower(strings.TrimSpace(s))
		if s == "" {
			continue
		}
		out[s] = struct{}{}
	}
	return out
}
