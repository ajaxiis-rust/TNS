package cast

import "strings"

// LangProfile — профиль языка скана имён (P12 §5.9, шаг 1). Данные, а не код:
// стоп-листы служебных слов и топонимов, словарь нарицательных и маркеры
// атрибуции реплик. Профиль расширяется файлом без правки скана.
type LangProfile struct {
	// Lang — код языка профиля.
	Lang string

	// FunctionLemmas — служебные слова (предлоги, союзы, частицы,
	// местоимения): кандидатом не считаются, даже написанные с заглавной.
	FunctionLemmas []string

	// ToponymLemmas — стоп-лист топонимов: места не становятся героями.
	ToponymLemmas []string

	// CommonLemmas — словарь нарицательных: токен с такой леммой именем не
	// считается, хотя бы форма и была с заглавной.
	CommonLemmas []string

	// SpeechLemmas — леммы глаголов речи для атрибуции реплик: «сказать»,
	// «ответить», «спросить», «кричать»…
	SpeechLemmas []string
}

// Profile возвращает профиль языка lang; ok=false — профиля нет.
func Profile(lang string) (LangProfile, bool) {
	p, ok := profiles[strings.ToLower(lang)]
	return p, ok
}

