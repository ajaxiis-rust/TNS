function close(ring: Ring): Ring {
  const first = ring[0];
  const last = ring[ring.length - 1];
  if (!first || !last) return ring;
  if (first[0] === last[0] && first[1] === last[1]) return ring;
  return [...ring, first];
}

/** d3-geo 3 treats a clockwise lon/lat ring as the small interior. */
function ensureRing(ring: Ring): Ring {
  const closed = close(ring);
  let sum = 0;
  for (let i = 0; i < closed.length - 1; i++) {
    sum += closed[i][0] * closed[i + 1][1] - closed[i + 1][0] * closed[i][1];
  }
  if (sum > 0) return [...closed].reverse();
  return closed;
}

function geometry(rings: Ring[]): Polygon | MultiPolygon {
  const fixed = rings.map(ensureRing);
  if (fixed.length === 1) return { type: "Polygon", coordinates: [fixed[0]] };
  return { type: "MultiPolygon", coordinates: fixed.map((ring) => [ring]) };
}

type Seed = Omit<Polity, "feature" | "outside"> & {
  outside?: boolean;
  rings: Ring[];
};

function make(seed: Seed): Polity {
  const { rings, outside, ...rest } = seed;
  return {
    ...rest,
    outside: Boolean(outside),
    feature: {
      type: "Feature",
      properties: { id: seed.id },
      geometry: geometry(rings),
    },
  };
}

